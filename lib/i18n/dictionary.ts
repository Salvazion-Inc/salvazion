export type Dictionary = (typeof dictionary)['es'];
export type DictLang = Language;

/** Resolve nested key path like "nav.home" */
export function translate(
  lang: Language,
  key: string,
  vars?: Record<string, string | number>
): string {
  const parts = key.split('.');
  // English is principal; fall back EN → ES → key
  let node: unknown = dictionary[lang] ?? dictionary.en;
  for (const p of parts) {
    if (node && typeof node === 'object' && p in (node as object)) {
      node = (node as Record<string, unknown>)[p];
    } else {
      node = undefined;
      break;
    }
  }
  if (typeof node !== 'string') {
    const fallbacks =
      lang === 'en'
        ? [dictionary.es, dictionary.pt]
        : lang === 'pt'
          ? [dictionary.es, dictionary.en]
          : [dictionary.en, dictionary.pt];
    for (const dict of fallbacks) {
      node = dict;
      let ok = true;
      for (const p of parts) {
        if (node && typeof node === 'object' && p in (node as object)) {
          node = (node as Record<string, unknown>)[p];
        } else {
          ok = false;
          break;
        }
      }
      if (ok && typeof node === 'string') break;
      node = undefined;
    }
  }
  if (typeof node !== 'string') return key;
  let out = node;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return out;
}
