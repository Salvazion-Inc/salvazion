function clean(s) {
  return s
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([,:;.!?])/g, '$1')
    .replace(/\s+'/g, "'")
    .trim();
}

function capFirst(s) {
  if (!s) return s;
  return s[0].toUpperCase() + s.slice(1);
}

function translateTitle(en) {
  let t = en || '';
  for (const [re, rep] of TITLE_PHRASES) t = t.replace(re, rep);
  if (/\b(the|and|of|for|with|about|from|in|to)\b/i.test(t)) {
    for (const [re, rep] of TITLE_WORDS) t = t.replace(re, rep);
  }
  return capFirst(clean(t));
}

function translatePreview(en) {
  let t = en || '';
  for (const [re, rep] of PREVIEW_OPENERS) {
    if (re.test(t)) {
      t = t.replace(re, rep);
      break;
    }
  }
  for (const [re, rep] of PREVIEW_WORDS) t = t.replace(re, rep);
  t = clean(t);
  t = capFirst(t);
  if (t.length > 320) t = t.slice(0, 317).replace(/\s+\S*$/, '') + '…';
  return t;
}

